"""Portfolio accounting: cash, positions, realized/unrealized P&L, equity curve.

Handles both equities and multi-leg option positions. Short positions are tracked
with negative signed quantities; realized P&L is booked whenever a position is
reduced or closed (including by expiration settlement).
"""

from __future__ import annotations

from dataclasses import dataclass, field

import pandas as pd

from backtesting_engine.core.types import Fill, Instrument


@dataclass
class Position:
    """A net position in a single instrument.

    ``quantity`` is signed (negative == short). ``avg_price`` is the per-unit cost
    basis of the currently-open quantity (commissions are expensed to cash, not
    capitalized into the basis, matching how brokers report realized P&L).
    """

    instrument: Instrument
    quantity: float = 0.0
    avg_price: float = 0.0

    @property
    def is_open(self) -> bool:
        return abs(self.quantity) > 1e-9

    def market_value(self, price: float) -> float:
        """Mark-to-market value of the open position in dollars."""
        return self.quantity * price * self.instrument.multiplier

    def unrealized_pnl(self, price: float) -> float:
        return (price - self.avg_price) * self.quantity * self.instrument.multiplier


@dataclass
class Portfolio:
    """Tracks cash, open positions, realized P&L and the equity curve over time."""

    starting_cash: float = 100_000.0
    cash: float = field(init=False)
    positions: dict[Instrument, Position] = field(default_factory=dict)
    realized_pnl: float = 0.0
    _equity_index: list[pd.Timestamp] = field(default_factory=list)
    _equity_values: list[float] = field(default_factory=list)
    _trades: list[dict[str, object]] = field(default_factory=list)

    def __post_init__(self) -> None:
        self.cash = self.starting_cash

    # -- positions --------------------------------------------------------
    def position(self, instrument: Instrument) -> Position:
        """Return the (possibly empty) position for ``instrument``."""
        return self.positions.get(instrument, Position(instrument=instrument))

    def apply_fill(self, fill: Fill, extra: dict[str, object] | None = None) -> float:
        """Apply a fill, update cash + position, and book realized P&L.

        Returns the realized P&L generated by this fill (non-zero only when the
        fill reduces or flips an existing position). ``extra`` columns (e.g. greeks
        captured at fill time) are merged into the trade-log row.
        """
        pos = self.positions.setdefault(fill.instrument, Position(instrument=fill.instrument))
        self.cash += fill.cash_flow

        signed = fill.signed_quantity
        mult = fill.instrument.multiplier
        realized = 0.0
        prev_qty = pos.quantity

        if prev_qty == 0 or (prev_qty > 0) == (signed > 0):
            # Opening or adding in the same direction: blend the average price.
            new_qty = prev_qty + signed
            if abs(new_qty) > 1e-9:
                pos.avg_price = (pos.avg_price * prev_qty + fill.price * signed) / new_qty
            pos.quantity = new_qty
        else:
            # Reducing, closing, or flipping: realize on the closed portion.
            closed = min(abs(signed), abs(prev_qty))
            direction = 1.0 if prev_qty > 0 else -1.0
            realized = (fill.price - pos.avg_price) * direction * closed * mult
            self.realized_pnl += realized
            new_qty = prev_qty + signed
            if (prev_qty > 0) != (new_qty > 0) and abs(new_qty) > 1e-9:
                # Position flipped past zero: remaining opens at the fill price.
                pos.avg_price = fill.price
            pos.quantity = new_qty
            if abs(new_qty) <= 1e-9:
                pos.quantity = 0.0

        row: dict[str, object] = {
            "timestamp": fill.timestamp,
            "symbol": fill.instrument.symbol,
            "asset_type": fill.instrument.asset_type.value,
            "right": fill.instrument.right.value if fill.instrument.right else None,
            "strike": fill.instrument.strike,
            "expiry": fill.instrument.expiry,
            "side": fill.side.value,
            "quantity": fill.quantity,
            "price": fill.price,
            "commission": fill.commission,
            "realized_pnl": realized,
            "tag": fill.tag,
        }
        if extra:
            row.update(extra)
        self._trades.append(row)
        if not pos.is_open:
            self.positions.pop(fill.instrument, None)
        return realized

    # -- valuation --------------------------------------------------------
    def positions_value(self, prices: dict[Instrument, float]) -> float:
        """Total mark-to-market value of all open positions."""
        total = 0.0
        for inst, pos in self.positions.items():
            price = prices.get(inst)
            if price is not None:
                total += pos.market_value(price)
        return total

    def total_equity(self, prices: dict[Instrument, float]) -> float:
        """Cash plus the marked value of open positions."""
        return self.cash + self.positions_value(prices)

    def record_equity(self, timestamp: pd.Timestamp, prices: dict[Instrument, float]) -> float:
        """Snapshot total equity at ``timestamp`` onto the equity curve."""
        equity = self.total_equity(prices)
        self._equity_index.append(timestamp)
        self._equity_values.append(equity)
        return equity

    # -- outputs ----------------------------------------------------------
    def equity_curve(self) -> pd.Series:
        """The recorded equity curve as a pandas Series indexed by timestamp."""
        return pd.Series(
            self._equity_values,
            index=pd.DatetimeIndex(self._equity_index, name="date"),
            name="equity",
            dtype="float64",
        )

    def trade_log(self) -> pd.DataFrame:
        """Per-fill trade log as a DataFrame."""
        columns = [
            "timestamp",
            "symbol",
            "asset_type",
            "right",
            "strike",
            "expiry",
            "side",
            "quantity",
            "price",
            "commission",
            "realized_pnl",
            "tag",
        ]
        if not self._trades:
            return pd.DataFrame(columns=columns)
        df = pd.DataFrame(self._trades)
        # Keep the canonical columns first, then any extra columns (e.g. greeks
        # captured at fill, or the expiration event marker) in insertion order.
        extras = [c for c in df.columns if c not in columns]
        return df[[*columns, *extras]]
